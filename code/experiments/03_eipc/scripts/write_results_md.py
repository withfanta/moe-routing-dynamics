"""Render artifacts/EIPC_P0/RESULTS.md from results.json. No new statistic."""
import json, os
ART=os.path.join(os.path.dirname(__file__),"..","artifacts","EIPC_P0")
r=json.load(open(os.path.join(ART,"results.json"))); T=r["targets"]
L=[]
L.append("# EIPC-P0 Results\n")
L.append("Expert-Identity Preservation Cache Pilot. An information-content experiment.")
L.append("The verdict follows the five-condition rule committed in")
L.append("`protocols/EIPC_P0_PREREGISTRATION.md` before these numbers existed.\n")
L.append("## Provenance\n")
L.append(f"- model: `{r['model_id']}` revision `{r['model_revision']}`, frozen, FP16, not quantized")
L.append(f"- data: WikiText-103-raw **{r['dataset_split_used']}** split (fresh; prior projects never used it)")
L.append(f"- manifest sha256: `{r['data_manifest_sha256']}`")
L.append(f"- FIT fingerprint: `{r['fit_fingerprint'][:32]}…`")
L.append(f"- TEST fingerprint: `{r['test_fingerprint'][:32]}…`")
L.append(f"- fixed projection: R^2048 -> R^{r['projection']['out_dim']}, seed {r['projection']['seed']}, sha256 `{r['projection']['sha256']}`")
L.append(f"- compression: {r['compression']}")
L.append(f"- probe: `{r['probe']}`; shuffle seed {r['shuffle_seed']}")
gp=sorted({T[k].get('gpu','') for k in T} - {''})
L.append(f"- n_fit = {T['8']['n_fit']}, n_test = {T['8']['n_test']}, probe input {T['8']['input_dim']}-d, target {T['8']['target_dim']}-d\n")
L.append("## Primary result\n")
L.append("| target | history | R² fused | R² identity | R² shuffled | A | B |")
L.append("|---|---|---|---|---|---|---|")
for k in ("8","12"):
    t=T[k]; h=f"L{min(t['history_layers'])}–{max(t['history_layers'])}"
    L.append(f"| Layer {k} | {h} | {t['R2_fused']:+.5f} | {t['R2_identity']:+.5f} | "
             f"{t['R2_shuffled']:+.5f} | **{t['A']:+.5f}** | **{t['B']:+.5f}** |")
L.append(f"\n- **mean A = {r['mean_A']:+.5f}**  (identity vs early fusion)")
L.append(f"- **mean B = {r['mean_B']:+.5f}**  (identity vs identity-destroyed control)\n")
L.append("Raw dimensions before the shared 64-d compression:\n")
L.append("| target | FUSED | EXPERT_IDENTITY / SHUFFLED_IDENTITY |")
L.append("|---|---|---|")
for k in ("8","12"):
    rd=T[k]["raw_dims"]
    L.append(f"| Layer {k} | {rd['FUSED']} | {rd['EXPERT_IDENTITY']} |")
L.append("\n## Verdict\n")
L.append(f"**{r['final_verdict']}**\n")
L.append("| condition | requirement | observed | outcome |")
L.append("|---|---|---|---|")
for c in r["conditions"]:
    L.append(f"| {c['condition']} | {c['requirement']} | {c['observed']} | **{'PASS' if c['passed'] else 'FAIL'}** |")
L.append("\nAll five conditions pass.\n")
L.append(f"{r['decision_sentence']}\n")
L.append("## Reading the result — and its limits\n")
L.append("Both A and B are positive at both depths, and the effect is larger at the later")
L.append("target (Layer 12) than the middle one (Layer 8). Three checks were run after the")
L.append("verdict was recorded, to test whether the positive result is an artifact rather")
L.append("than the phenomenon. All are diagnostic only and changed nothing.\n")
L.append("**No target leakage.** History for each target is strictly earlier than the target")
L.append("layer (Layers 1–7 for target 8, Layers 1–11 for target 12), verified against the")
L.append("frozen layer indices.\n")
L.append("**Not a PCA-capacity artifact.** FUSED inputs are full rank (224 and 352) and every")
L.append("representation receives the identical 64-component budget, so FUSED is not starved")
L.append("of components relative to EXPERT_IDENTITY.\n")
L.append("**The control behaves as specified.** Shuffling preserves the per-layer vector sum")
L.append("to 4.8e-07, the same vector multiset, and the same occupied-slot count; only which")
L.append("expert slot holds which vector changes.\n")
L.append("**The most important caveat.** `R2_shuffled` is approximately zero at both targets")
L.append("even though the fused sum remains arithmetically recoverable from the shuffled")
L.append("slots. The reason is that the cyclic shift varies per sample and per layer, so a")
L.append("*linear* probe on 64 PCA components cannot undo it. B therefore measures the value")
L.append("of expert identity **to this probe class under this compression**, not an")
L.append("information-theoretic bound. B being much larger than A should be read in that")
L.append("light: A is the more conservative of the two quantities, since FUSED and")
L.append("EXPERT_IDENTITY are both linearly accessible to the probe.\n")
L.append("## Interpretation limit\n")
L.append(f"{r['stopping_note']}\n")
L.append("This is a screening result about information content under one frozen setting. It")
L.append("does not show that an expert-state cache would improve language-model accuracy,")
L.append("latency, or memory cost, and it is not evidence about any specific architecture.\n")
L.append("## Relationship to the closed prior projects\n")
L.append(f"The prior rejected-expert projects are {r['prior_projects_status']}. EIPC-P0 asks a")
L.append("different question about *selected*-expert provenance, executed no rejected experts,")
L.append("used no counterfactual routing or routing regret, and imported no prior conclusion.\n")
L.append(f"Rescue modifications: {r['rescue_modifications']}.\n")
open(os.path.join(ART,"RESULTS.md"),"w").write("\n".join(L))
print("RESULTS.md written")
