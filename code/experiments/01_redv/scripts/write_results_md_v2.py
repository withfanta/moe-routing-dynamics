"""Render artifacts/REDV_V2/RESULTS.md from results.json. No new statistic."""
import json, os

ART = os.path.join(os.path.dirname(__file__), "..", "artifacts", "REDV_V2")
r = json.load(open(os.path.join(ART, "results.json")))
L = []
L.append("# REDV-V2 Results\n")
L.append("Dimension-Matched Rejected-Evidence Test. The single, final authorized")
L.append("follow-up to REDV-V1. Verdict follows the rule committed in")
L.append("`protocols/REDV_V2_PREREGISTRATION.md` before these numbers existed.\n")
L.append("## Provenance\n")
L.append(f"- model: `{r['model_id']}` revision `{r['model_revision']}`")
L.append(f"- GPU: {r['gpu']} (FP16, `torch.inference_mode()`, frozen, not quantized)")
L.append("- data: WikiText-103-raw, untouched blocks only; every REDV-V1 block excluded; train unused")
L.append(f"- data manifest sha256: `{r['data_manifest_sha256']}`")
L.append(f"- fit fingerprint: `{r['fit_fingerprint'][:32]}…`")
L.append(f"- test fingerprint: `{r['test_fingerprint'][:32]}…`")
L.append(f"- sampling seed {r['v2_seed']}, shuffle seed {r['shuffle_seed']}")
L.append(f"- probe: `{r['probe']}`\n")
L.append("## The matched comparison\n")
L.append("REDV-V1's confound was a dimensionality gap (2112 vs 4160 at n=512). REDV-V2")
L.append("compares two **equal-dimension 4160-d** models under identical Ridge, identical")
L.append("alpha, and identical preprocessing:\n")
L.append("    REAL:     [b_i ; r_i]")
L.append("    CONTROL:  [b_i ; r_perm(i)]      one fixed derangement, seed 314159\n")
L.append("The control preserves dimensionality, empirical distribution, scale, and")
L.append("within-vector covariance. It destroys only the sample-specific correspondence")
L.append("between rejected evidence and routing regret.\n")
L.append("## Primary result\n")
L.append("| transition | R² baseline | R² real | R² shuffled | D | real − baseline |")
L.append("|---|---|---|---|---|---|")
for t in r["transitions"]:
    L.append(f"| {t['transition_human']} | {t['R2_baseline']:+.5f} | {t['R2_real']:+.5f} | "
             f"{t['R2_shuffle']:+.5f} | **{t['D']:+.5f}** | {t['gain_over_baseline']:+.5f} |")
L.append(f"\n**mean D = {r['mean_D']:+.5f}**\n")
L.append(f"n_fit = {r['transitions'][0]['n_fit']}, n_test = {r['transitions'][0]['n_test']} per transition.\n")
L.append("## Routing regret (descriptive only)\n")
L.append("| transition | mean G | median G | proportion G > 0 |")
L.append("|---|---|---|---|")
for t in r["transitions"]:
    L.append(f"| {t['transition_human']} | {t['mean_G']:.5f} | {t['median_G']:.5f} | "
             f"{t['proportion_G_positive']:.4f} |")
L.append("\n## Verdict\n")
L.append(f"**{r['final_verdict']}**\n")
L.append("Mechanical application of the pre-registered rule:\n")
L.append("| condition | requirement | outcome |")
L.append("|---|---|---|")
reals = [t["R2_real"] for t in r["transitions"]]
ds = [t["D"] for t in r["transitions"]]
c1 = "PASS" if all(v > 0 for v in reals) else "FAIL"
c2 = "PASS" if all(d > 0 for d in ds) else "FAIL"
c3 = "PASS" if r["mean_D"] >= 0.02 else "FAIL"
L.append(f"| 1 | R²_real > 0 for all three | **{c1}** — all three negative |")
L.append(f"| 2 | D > 0 for all three | **{c2}** — negative at 4→5 and 8→9 |")
L.append(f"| 3 | mean(D) ≥ +0.02 | **{c3}** — mean D = {r['mean_D']:+.5f} |")
L.append("\nAll three conditions fail. Any single failure yields NOT_SUPPORTED.\n")
L.append("### Reading the result\n")
L.append("Two independent reasons the premise is unsupported:\n")
L.append("1. **The regressors are unusable.** Every R²_real is negative, so the real-augmented")
L.append("   probe predicts held-out regret worse than the test-set mean. Condition 1 exists")
L.append("   precisely to block a success claim resting on two unusable regressors.")
L.append("2. **Matched control beats real evidence.** At 4→5 and 8→9 the shuffled control")
L.append("   scores *higher* than correctly matched evidence (D = −0.196, −0.132). Rejected")
L.append("   evidence from another sample predicts regret no worse — in fact better — than a")
L.append("   sample's own. The small positive D at 12→13 (+0.029) does not survive the rule,")
L.append("   and is not interpreted separately.\n")
L.append("The large positive `real − baseline` column (+2.44, +1.02, +0.79) is exactly the")
L.append("REDV-V1 artifact reproduced: adding 2048 columns to a p≫n Ridge shrinks predictions")
L.append("toward the mean and lifts a very negative R² toward zero. Against the")
L.append("dimension-matched control that apparent gain disappears, which is what REDV-V2 was")
L.append("built to detect.\n")
L.append(f"{r['stopping_note']}\n")
L.append("## Relationship to REDV-V1\n")
L.append(f"REDV-V1's verdict remains permanently recorded as **{r['redv_v1_verdict_unchanged']}**")
L.append("and is not changed. Its artifacts were read-only throughout REDV-V2.\n")
L.append(f"Rescue modifications: {r['rescue_modifications']}.\n")
open(os.path.join(ART, "RESULTS.md"), "w").write("\n".join(L))
print("RESULTS.md written")
