"""Render artifacts/DREV_P0/RESULTS.md from results.json. No new statistic."""
import json, os
ART = os.path.join(os.path.dirname(__file__), "..", "artifacts", "DREV_P0")
r = json.load(open(os.path.join(ART, "results.json")))
H = r["horizons"]
L = []
L.append("# DREV-P0 Results\n")
L.append("Delayed Rejected-Evidence Value Pilot. A small screening experiment. The verdict")
L.append("follows the four-condition rule committed in")
L.append("`protocols/DREV_P0_PREREGISTRATION.md` before these numbers existed.\n")
L.append("## Provenance\n")
L.append(f"- model: `{r['model_id']}` revision `{r['model_revision']}`, frozen, FP16, not quantized")
L.append(f"- source layer: Layer {r['source_layer']} (code {r['source_layer_code']})")
L.append("- data: WikiText-103-raw, only blocks never used by REDV-V1 or REDV-V2")
L.append(f"- untouched pool: {r['untouched_pool_size']} blocks; prior excluded: {r['prior_blocks_excluded']}")
L.append(f"- manifest sha256: `{r['data_manifest_sha256']}`")
L.append(f"- fit fingerprint: `{r['fit_fingerprint'][:32]}…`")
L.append(f"- test fingerprint: `{r['test_fingerprint'][:32]}…`")
L.append(f"- compression: {r['compression']}")
L.append(f"- probe: `{r['probe']}`, shuffle seed {r['shuffle_seed']}")
gpus = sorted({H[k]['gpu'] for k in H})
L.append(f"- GPUs: {', '.join(gpus)} (two independent single-GPU workers, no DDP)\n")
L.append("## Primary result\n")
L.append("| Δ | target layer | R² real | R² shuffled | D |")
L.append("|---|---|---|---|---|")
for k in ("1", "2", "4", "8"):
    h = H[k]
    L.append(f"| {k} | {h['target_layer']} | {h['R2_real']:+.5f} | {h['R2_shuffle']:+.5f} | **{h['D']:+.5f}** |")
L.append(f"\n- **mean D over delayed horizons (Δ = 2, 4, 8) = {r['mean_D_delayed']:+.5f}**")
L.append(f"- immediate D (Δ = 1) = {r['D_immediate']:+.5f}\n")
L.append(f"n_fit = {H['1']['n_fit']}, n_test = {H['1']['n_test']} per horizon; probe dim {H['1']['probe_dim']}.\n")
L.append("## Routing regret (descriptive only)\n")
L.append("| Δ | target layer | mean G | median G | proportion G > 0 |")
L.append("|---|---|---|---|---|")
for k in ("1", "2", "4", "8"):
    h = H[k]
    L.append(f"| {k} | {h['target_layer']} | {h['mean_G']:.5f} | {h['median_G']:.5f} | {h['proportion_G_positive']:.4f} |")
L.append("\n## Verdict\n")
L.append(f"**{r['final_verdict']}**\n")
L.append("Mechanical application of the frozen rule:\n")
L.append("| condition | requirement | observed | outcome |")
L.append("|---|---|---|---|")
for c in r["conditions"]:
    L.append(f"| {c['condition']} | {c['requirement']} | {c['observed']} | **{'PASS' if c['passed'] else 'FAIL'}** |")
L.append("\nAll four conditions fail. Any single failure yields NOT_PROMISING.\n")
L.append("### Reading the result\n")
L.append("The pilot asked whether Layer-4 rejected evidence becomes *more* informative about")
L.append("routing regret at later depths than at the immediate next layer. It does not.\n")
L.append("Every `R2_real` is negative, so at no horizon does the real-augmented probe predict")
L.append("held-out regret better than the test-set mean. Every `D` is negative, so at every")
L.append("horizon the derangement control — rejected evidence belonging to a *different*")
L.append("sample — predicts regret at least as well as a sample's own. And the delayed mean")
L.append("is more negative than the immediate value, so there is no sign of information")
L.append("emerging with depth; if anything the gap widens against the hypothesis, with the")
L.append("most negative D at the largest distance (Δ = 8, D = -0.10895).\n")
L.append("The compression worked as intended: at 128 dimensions against n = 512 the probes are")
L.append("no longer in the p >> n regime that made the earlier REDV measurement")
L.append("uninterpretable, and the R² values are now close to zero rather than large and")
L.append("negative. The matched comparison is therefore readable, and it reads negative.\n")
L.append("Routing regret itself is present and non-trivial at every horizon (mean G ≈ 0.047 to")
L.append("0.054, positive for roughly 74-78% of samples), so the null result is not caused by")
L.append("an absent or degenerate target.\n")
L.append("## Interpretation limit\n")
L.append(f"{r['stopping_note']}\n")
L.append("This is a screening result under one frozen pilot setting, not a universal theorem.")
L.append("It does not prove that no delayed cross-layer signal exists anywhere; it says this")
L.append("pilot found none, and the pre-registered rule therefore stops the hypothesis.\n")
L.append("## Relationship to the closed REDV project\n")
L.append(f"REDV is {r['redv_project_status']}. DREV-P0 reused validated REDV implementation only")
L.append("(commits listed in `README.md`) and imported none of its conclusions.\n")
L.append(f"Rescue modifications: {r['rescue_modifications']}.\n")
open(os.path.join(ART, "RESULTS.md"), "w").write("\n".join(L))
print("RESULTS.md written")
